export const meta = {
  name: 'studio-spec',
  description: 'Research a VEER Studio OS target and write a build-ready spec for user review',
  whenToUse: 'Turn docs/studio-os/briefs/<target>.md into docs/studio-os/specs/<target>.md. Args: { target: "foundation" | "clients" | "finance" | "projects" }',
  phases: [
    { title: 'Research', detail: 'one reader per research question in the brief' },
    { title: 'Draft', detail: 'two independent designs: lean and durable' },
    { title: 'Synthesize', detail: 'merge into one spec with a work breakdown' },
    { title: 'Critique', detail: 'constraint and buildability critics, then revise' },
  ],
}

const target = typeof args === 'string' ? args : args && args.target
if (!target) throw new Error('Pass args: { target: "foundation" }')

const ROOT = '/Users/shahriar/Developer/veer.studio/products/os'
const CANON = 'docs/studio-os/architecture.md'
const BRIEF = `docs/studio-os/briefs/${target}.md`
const SPEC = `docs/studio-os/specs/${target}.md`
const FENCE = '`'.repeat(3)

const RULES = `Repo root: ${ROOT}. Canon: ${CANON} — read it first. Its Decisions are settled by the user; do not re-litigate them. Upstream source is the pinned submodule cloudflare-os/ — read-only, never edit it. Hard rules: never deploy, never run wrangler deploy/secret/delete/rollback/versions commands, never change Cloudflare, Access or Email Routing configuration, never git commit/push/switch branches. Cite evidence as path + identifier; line numbers drift.`

const SPEC_TEMPLATE = `Spec structure (use these headings, in order; write "n/a" where a section does not apply):
# Spec: ${target}
Status line: "Draft for user review · generated by studio-spec".
## 1. Summary
## 2. Inherited decisions — only the canon decisions that shape this spec, linked to ${CANON}
## 3. Design — components, domain model and data, whichever fits the target
## 4. Agent surface — types.d.ts sketch; which reads are observations; action kinds as a table (tag, autoApprovable, delivery, description fields); agent catalog; slash commands
## 5. App surface — the flat ui method list; screens; admin gating; what the audit log records
## 6. Storage — Durable Objects and their names, tables, migrations, revoke() behaviour
## 7. Integration — APIs exposed to or consumed from other gates
## 8. Deployment — deployment.jsonc keys, Worker name, binding, deploy order, compatibility flags, rollback
## 9. Verification — automated tests; manual checklist for a signed-in browser session after deploy
## 10. Risks and open questions for the user
## 11. Work breakdown — exactly one ${FENCE}json block: {"packages":[{"id","title","paths","dependsOn","instructions","acceptance"}]}
Work breakdown rules: 3–7 packages. "paths" are repo-relative files or globs owned EXCLUSIVELY by that package — no two packages may own the same or overlapping paths, because packages are built concurrently. The first package (empty dependsOn) owns every dependency file (root package.json, pnpm-workspace.yaml, pnpm-lock.yaml) plus each new package's package.json, adds every new dependency and runs pnpm install; no other package adds dependencies or runs pnpm install. "instructions" must be self-sufficient for an agent that has read only the canon and this spec. Each "acceptance" item must be checkable by running a command or reading code.`

phase('Research')
const scope = await agent(
  `${RULES}

Read ${CANON} and the brief ${BRIEF}. Return the research questions to investigate before designing "${target}": use the brief's "Research questions" verbatim, and add at most two more only if a deliverable or acceptance criterion cannot be designed without them. For each, say where to look (paths, packages, Drive files, URLs).`,
  {
    label: 'scope',
    schema: {
      type: 'object',
      properties: {
        questions: {
          type: 'array',
          items: {
            type: 'object',
            properties: { id: { type: 'string' }, question: { type: 'string' }, lookAt: { type: 'string' } },
            required: ['id', 'question', 'lookAt'],
          },
        },
      },
      required: ['questions'],
    },
  },
)
if (!scope || !scope.questions.length) throw new Error(`No research questions found in ${BRIEF}`)
log(`${scope.questions.length} research questions for ${target}`)

const research = (await pipeline(scope.questions, (q) =>
  agent(
    `${RULES}

READ-ONLY research for the "${target}" spec (brief: ${BRIEF}). Do not modify any file.
Question ${q.id}: ${q.question}
Start at: ${q.lookAt}
Answer from source, densely: what exists, exactly how it works, what the design should reuse or copy, and traps. Every factual claim needs evidence (path + identifier, or URL). List what you could not determine.`,
    {
      label: `research:${q.id}`,
      phase: 'Research',
      schema: {
        type: 'object',
        properties: {
          id: { type: 'string' },
          answer: { type: 'string' },
          facts: {
            type: 'array',
            items: { type: 'object', properties: { claim: { type: 'string' }, evidence: { type: 'string' } }, required: ['claim', 'evidence'] },
          },
          unknowns: { type: 'array', items: { type: 'string' } },
        },
        required: ['id', 'answer', 'facts', 'unknowns'],
      },
    },
  ),
)).filter(Boolean)

const dropped = scope.questions.length - research.length
if (dropped) log(`${dropped} research question(s) returned nothing; drafts proceed without them`)

const digest = research
  .map((r) => `### ${r.id}\n${r.answer}\n\nEvidence:\n${r.facts.map((f) => `- ${f.claim} — ${f.evidence}`).join('\n')}\n\nUnknown: ${r.unknowns.join('; ') || 'none'}`)
  .join('\n\n')

phase('Draft')
const ANGLES = [
  { key: 'lean', lens: 'LEAN: the smallest design that meets every deliverable and acceptance criterion in the brief. Prefer copying proven upstream code over new abstractions; defer anything not required.' },
  { key: 'durable', lens: 'DURABLE: design for the targets that will build on this one. Shape every shared API, store and convention so later gates (Clients, Finance, Projects) use it without rework, while still building only what the brief asks for.' },
]
const drafts = (await parallel(ANGLES.map((a) => () =>
  agent(
    `${RULES}

Write an independent draft spec for "${target}". Angle — ${a.lens}
Read ${CANON} and ${BRIEF}, then use the research digest below (verify anything you rely on that looks doubtful). Return the full draft as markdown text; do NOT write any file.

${SPEC_TEMPLATE}

Research digest:
${digest}`,
    { label: `draft:${a.key}`, phase: 'Draft' },
  ),
))).filter(Boolean)
if (!drafts.length) throw new Error('Both drafts failed')

phase('Synthesize')
const synth = await agent(
  `${RULES}

Synthesize the final spec for "${target}" and WRITE it to ${SPEC} (create directories as needed). This is the only file you may write.
Start from the stronger draft, graft the better ideas from the other, and resolve every disagreement explicitly, citing evidence. Where the drafts disagree on something only the user can decide, put it in section 10 with a recommendation instead of guessing.

${SPEC_TEMPLATE}

${drafts.map((d, i) => `===== Draft ${ANGLES[i] ? ANGLES[i].key : i} =====\n${d}`).join('\n\n')}

===== Research digest =====
${digest}`,
  {
    label: 'synthesize',
    phase: 'Synthesize',
    schema: {
      type: 'object',
      properties: { specPath: { type: 'string' }, packageCount: { type: 'number' }, summary: { type: 'string' } },
      required: ['specPath', 'packageCount', 'summary'],
    },
  },
)
if (!synth) throw new Error('Synthesis failed')

phase('Critique')
const FINDINGS = {
  type: 'object',
  properties: {
    findings: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          issue: { type: 'string' },
          evidence: { type: 'string' },
          fix: { type: 'string' },
          severity: { type: 'string', enum: ['high', 'medium', 'low'] },
        },
        required: ['issue', 'evidence', 'fix', 'severity'],
      },
    },
  },
  required: ['findings'],
}
const CRITICS = [
  { key: 'constraints', prompt: `Check every design choice and factual claim in ${SPEC} against ${CANON} and the upstream source. Try to REFUTE each: does the contract really allow it at this pin, does it violate a settled decision (identity conventions, no stalling action kinds, admin-only/restricted rules, Kumo, independent Workers), would it break the byte-identical generated-config rule or deploy safety? Report only real problems, with evidence.` },
  { key: 'buildability', prompt: `Check that ${SPEC} can be built by independent agents: every brief deliverable and acceptance criterion in ${BRIEF} is covered; section 11's work packages own disjoint paths, have correct dependsOn, follow the dependency-file rule, have self-sufficient instructions and command-checkable acceptance; nothing needed is owned by nobody. Report gaps, with evidence.` },
]
const critiques = (await parallel(CRITICS.map((c) => () =>
  agent(`${RULES}\n\nREAD-ONLY review; do not modify files.\n${c.prompt}`, { label: `critic:${c.key}`, phase: 'Critique', schema: FINDINGS })
    .then((r) => (r ? r.findings.map((f) => ({ ...f, critic: c.key })) : [])),
))).filter(Boolean).flat()
log(`${critiques.length} critique finding(s)`)

const revision = await agent(
  `${RULES}

Revise ${SPEC} in place using the critique findings below. For each: apply it if it is correct (verify against source first), or reject it with a reason. Keep the template structure. Append a final "## Revision notes" section listing what changed and what was rejected. Make section 10 the definitive list of questions the user must answer before building.

Findings:
${JSON.stringify(critiques, null, 2)}`,
  {
    label: 'revise',
    phase: 'Critique',
    schema: {
      type: 'object',
      properties: {
        applied: { type: 'number' },
        rejected: { type: 'number' },
        openQuestions: { type: 'array', items: { type: 'string' } },
        summary: { type: 'string' },
      },
      required: ['applied', 'rejected', 'openQuestions', 'summary'],
    },
  },
)

return {
  target,
  spec: SPEC,
  packages: synth.packageCount,
  researchAnswered: research.length,
  researchDropped: dropped,
  critiqueFindings: critiques.length,
  revision,
}
