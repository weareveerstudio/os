// Copies the Workshop's Kumo token overrides into `app/tokens.css`, so studio apps match the
// Workshop around them and follow it on every submodule bump.
//
//   node build/tokens.ts           report whether app/tokens.css is current (exit 1 if not)
//   node build/tokens.ts --write   regenerate it
//
// `__tests__/node/tokens.test.ts` runs the same comparison, so a bump that changes the Workshop's
// tokens fails `pnpm test` until this is rerun.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** The Workshop stylesheet the tokens come from. */
export const WORKSHOP_STYLES = resolve(
  packageDirectory, "../../cloudflare-os/packages/workshop-frontend/src/styles.css");

/** The generated file. */
export const TOKENS_FILE = resolve(packageDirectory, "app/tokens.css");

// Light mode: Kumo's semantic colours, plus the fonts and the Tailwind text sizes the Workshop
// restores over Kumo's. Dark mode: the semantic colours only.
const LIGHT = /^--(?:color-kumo-|text-color-kumo-|font-(?:sans|mono)$|text-(?:xs|sm|base|lg)(?:--line-height)?$)/;
const DARK = /^--(?:color-kumo-|text-color-kumo-)/;

/**
 * Returns the body of the first top-level block whose selector line is exactly `selector`.
 * @param css Stylesheet text.
 * @param selector `@theme` or `[data-mode="dark"]`.
 * @returns The text between the braces.
 */
function block(css: string, selector: string): string {
  const start = css.search(new RegExp(`^${selector.replace(/[[\]"=]/g, "\\$&")} \\{$`, "m"));
  if (start < 0) throw new Error(`No "${selector} {" block in the Workshop stylesheet.`);
  const open = css.indexOf("{", start);
  let depth = 0;
  for (let i = open; i < css.length; i++) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}" && --depth === 0) return css.slice(open + 1, i);
  }
  throw new Error(`Unterminated "${selector}" block in the Workshop stylesheet.`);
}

function declarations(body: string, keep: RegExp): [string, string][] {
  return body
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .split(";")
    .map((part) => part.trim())
    .filter(Boolean)
    .map((part): [string, string] => {
      const colon = part.indexOf(":");
      return [part.slice(0, colon).trim(), part.slice(colon + 1).replace(/\s+/g, " ").trim()];
    })
    .filter(([name]) => keep.test(name));
}

function lines(entries: [string, string][]): string {
  return entries.map(([name, value]) => `  ${name}: ${value};`).join("\n");
}

/**
 * Renders `tokens.css` from the Workshop's stylesheet.
 * @param workshopCss The Workshop's `styles.css`.
 * @returns The file contents.
 */
export function renderTokens(workshopCss: string): string {
  const light = declarations(block(workshopCss, "@theme"), LIGHT);
  const dark = declarations(block(workshopCss, '[data-mode="dark"]'), DARK);
  if (!light.length || !dark.length) throw new Error("Found no Kumo tokens to copy.");
  return [
    "/* Generated by packages/studio-kit/build/tokens.ts from",
    " * cloudflare-os/packages/workshop-frontend/src/styles.css. Do not edit; run",
    " * `node packages/studio-kit/build/tokens.ts --write` after a submodule bump. */",
    "@theme {",
    lines(light),
    "}",
    "",
    '[data-mode="dark"] {',
    lines(dark),
    "}",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const expected = renderTokens(readFileSync(WORKSHOP_STYLES, "utf8"));
  if (process.argv.includes("--write")) {
    writeFileSync(TOKENS_FILE, expected);
    console.log(`Wrote ${TOKENS_FILE}`);
  } else {
    let current = "";
    try {
      current = readFileSync(TOKENS_FILE, "utf8");
    } catch {
      // Missing reads as stale.
    }
    if (current !== expected) {
      console.error("app/tokens.css is stale: run `node packages/studio-kit/build/tokens.ts --write`.");
      process.exitCode = 1;
    } else {
      console.log("app/tokens.css matches the Workshop.");
    }
  }
}
